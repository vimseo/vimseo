"""The samples of a DOE used by a sensitivity analysis.

A sensitivity analysis either executes the DOE it needs
or uses the result of a DOE prepared in advance,
whose DOE algorithm is then checked.
"""

from __future__ import annotations

import logging
from typing import TYPE_CHECKING
from typing import Any

from gemseo.datasets.io_dataset import IODataset

from vimseo.analysis_nodes.doe.doe_result import DOEResult
from vimseo.core.model_metadata import MetaDataNames

if TYPE_CHECKING:
    from collections.abc import Sequence

    from gemseo.datasets.dataset import Dataset
    from gemseo.typing import RealArray


LOGGER = logging.getLogger(__name__)

UNSTRUCTURED_ALGO = "Unstructured"
"""The DOE algorithm of samples not generated by a known DOE algorithm,
e.g. measurements or runs searched in an archive."""


def to_doe_result(dataset: Dataset) -> DOEResult:
    """Wrap samples not generated by a known DOE algorithm into a DOE result.

    Args:
        dataset: The samples, with an input group and an output group.

    Returns:
        The DOE result, whose DOE algorithm is :data:`.UNSTRUCTURED_ALGO`.
    """
    doe_result = DOEResult(dataset=dataset)
    doe_result.metadata.settings = {"algo": UNSTRUCTURED_ALGO, "algo_settings": {}}
    return doe_result


def get_algo_settings(
    doe_result: DOEResult, algo_names: Sequence[str], analysis_name: str
) -> dict[str, Any]:
    """Return the settings of the DOE algorithm that generated the samples of a DOE.

    Args:
        doe_result: The result of the DOE.
        algo_names: The names of the DOE algorithms suitable for the analysis.
        analysis_name: The name of the sensitivity analysis.

    Returns:
        The settings of the DOE algorithm, other than the number of samples.

    Raises:
        ValueError: When the DOE algorithm is not suitable for the analysis.
    """
    algo_name = doe_result.metadata.settings.get("algo")
    if algo_name not in algo_names:
        generated_by = (
            "an unknown DOE algorithm" if algo_name is None else repr(algo_name)
        )
        msg = (
            f"The sensitivity analysis {analysis_name!r} requires the samples of a DOE "
            f"generated by {' or '.join(map(repr, algo_names))}, "
            f"whereas they were generated by {generated_by}."
        )
        raise ValueError(msg)

    return dict(doe_result.metadata.settings.get("algo_settings", {}))


def get_variable_names(dataset: Dataset, group_name: str) -> list[str]:
    """Return the names of the variables of a group, in the order of the columns.

    Contrary to :meth:`.Dataset.get_variable_names`, the names are not sorted:
    the samples of a DOE are ordered like the variables of its variables space,
    and a sensitivity analysis relies on this order.

    Args:
        dataset: The samples of the DOE.
        group_name: The name of the group.

    Returns:
        The names of the variables of the group.
    """
    return list(
        dataset
        .get_view(group_names=group_name)
        .columns.get_level_values(dataset.COLUMN_LEVEL_NAMES[1])
        .unique()
    )


def _check_groups(dataset: Dataset) -> None:
    """Check that the samples of a DOE have an input group and an output group.

    Args:
        dataset: The samples of the DOE.

    Raises:
        ValueError: When the DOE has no input group or no output group.
    """
    for group_name in (IODataset.INPUT_GROUP, IODataset.OUTPUT_GROUP):
        if group_name not in dataset.group_names:
            msg = (
                f"The samples of the DOE must have a group {group_name!r}; "
                f"its groups are {dataset.group_names}."
            )
            raise ValueError(msg)


def get_output_names(dataset: Dataset, output_names: Sequence[str] = ()) -> list[str]:
    """Return the names of the outputs of a DOE considered by a sensitivity analysis.

    Args:
        dataset: The samples of the DOE.
        output_names: The names of the outputs.
            If empty, use all the outputs of the DOE except the metadata of the model.

    Returns:
        The names of the outputs.

    Raises:
        ValueError: When the DOE has no input group or no output group,
            or when an output is missing from the DOE.
    """
    _check_groups(dataset)
    available_names = get_variable_names(dataset, IODataset.OUTPUT_GROUP)
    if not output_names:
        metadata_names = {name.name for name in MetaDataNames}
        return [name for name in available_names if name not in metadata_names]

    missing_names = set(output_names).difference(available_names)
    if missing_names:
        msg = (
            f"The outputs {sorted(missing_names)} are missing from the DOE, "
            f"whose outputs are {available_names}."
        )
        raise ValueError(msg)

    return list(output_names)


def to_io_dataset(dataset: Dataset, output_names: Sequence[str]) -> IODataset:
    """Restrict the samples of a DOE to its inputs and to some outputs.

    The other outputs, e.g. the metadata of the model, are removed.

    Args:
        dataset: The samples of the DOE,
            with an input group and an output group.
        output_names: The names of the outputs to keep.

    Returns:
        The samples of the DOE restricted to its inputs and to the outputs.

    Raises:
        ValueError: When the DOE has no input group or no output group.
    """
    _check_groups(dataset)
    io_dataset = IODataset(dataset_name=dataset.name)
    for group_name, names in (
        (IODataset.INPUT_GROUP, get_variable_names(dataset, IODataset.INPUT_GROUP)),
        (IODataset.OUTPUT_GROUP, output_names),
    ):
        for name in names:
            io_dataset.add_variable(
                name,
                dataset
                .get_view(group_names=group_name, variable_names=name)
                .to_numpy()
                .astype(float),
                group_name=group_name,
            )

    return io_dataset


def _get_nan_samples(dataset: Dataset) -> list:
    """Return the samples of a DOE with a NaN output, e.g. a failed evaluation.

    Args:
        dataset: The samples of the DOE.

    Returns:
        The index of the samples with a NaN output.
    """
    has_nan = dataset.get_view(group_names=IODataset.OUTPUT_GROUP).isna().any(axis=1)
    return list(dataset.index[has_nan.to_numpy()])


def check_no_nan_output(dataset: Dataset, analysis_name: str) -> None:
    """Check that the outputs of a DOE have no NaN.

    Args:
        dataset: The samples of the DOE.
        analysis_name: The name of the sensitivity analysis.

    Raises:
        ValueError: When an output has a NaN.
    """
    nan_samples = _get_nan_samples(dataset)
    if nan_samples:
        msg = (
            f"The sensitivity analysis {analysis_name!r} cannot use the samples "
            f"{nan_samples} of the DOE, whose outputs have NaN, "
            "e.g. failed evaluations of the model."
        )
        raise ValueError(msg)


def remove_nan_outputs(dataset: Dataset) -> None:
    """Remove the samples of a DOE with a NaN output, e.g. a failed evaluation.

    Args:
        dataset: The samples of the DOE, modified in place.
    """
    nan_samples = _get_nan_samples(dataset)
    if nan_samples:
        LOGGER.warning(
            "The samples %s of the DOE are removed since their outputs have NaN, "
            "e.g. failed evaluations of the model; "
            "the estimation is biased if the failures depend on the inputs.",
            nan_samples,
        )
        dataset.drop(index=nan_samples, inplace=True)


def get_input_samples(dataset: Dataset) -> RealArray:
    """Return the input samples of a DOE.

    Args:
        dataset: The samples of the DOE.

    Returns:
        The input samples, shaped as ``(n_samples, n_input_components)``.
    """
    return dataset.get_view(group_names=IODataset.INPUT_GROUP).to_numpy().astype(float)
